"""
SQLAlchemy ORM models for Score and CompositeScore entities.

Stores AI-generated scores for leads based on various criteria.
"""

import uuid
from datetime import datetime
from typing import TYPE_CHECKING, Optional

from sqlalchemy import DateTime, ForeignKey, Index, String, Text, Boolean, Float, Integer
from app.db.base import JSONType as JSONB, PortableUUID as UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base

if TYPE_CHECKING:
    from app.models.lead import Lead


class Score(Base):
    """
    ORM model for the scores table.

    Stores individual criterion scores for a lead generated by AI analysis.
    """

    __tablename__ = "scores"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        index=True,
    )
    lead_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("leads.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    criteria_name: Mapped[str] = mapped_column(String(100), nullable=False, index=True)
    score: Mapped[int] = mapped_column(Integer, nullable=False)  # 1-10 scale
    reasoning: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    cited_evidence: Mapped[Optional[dict]] = mapped_column(JSONB, nullable=True)
    confidence: Mapped[float] = mapped_column(Float, nullable=False)  # 0.0-1.0
    validation_warnings: Mapped[Optional[dict]] = mapped_column(JSONB, nullable=True)
    model_used: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    tokens_used: Mapped[Optional[int]] = mapped_column(Integer, nullable=True)
    latency_ms: Mapped[Optional[int]] = mapped_column(Integer, nullable=True)
    trace_id: Mapped[Optional[str]] = mapped_column(String(64), nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=False),
        default=datetime.utcnow,
        nullable=False,
    )

    # Relationships
    lead: Mapped["Lead"] = relationship("Lead", back_populates="scores")

    # Table indexes
    __table_args__ = (
        Index("ix_scores_lead_criteria", "lead_id", "criteria_name"),
    )

    def __repr__(self) -> str:
        """Return string representation of the Score."""
        return f"<Score(id={self.id}, lead_id={self.lead_id}, criteria={self.criteria_name}, score={self.score})>"


class CompositeScore(Base):
    """
    ORM model for the composite_scores table.

    Stores the aggregated/weighted score for a lead across all criteria.
    """

    __tablename__ = "composite_scores"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        index=True,
    )
    lead_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("leads.id", ondelete="CASCADE"),
        nullable=False,
        unique=True,
        index=True,
    )
    composite_score: Mapped[float] = mapped_column(Float, nullable=False)  # 0-100 scale
    overall_summary: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    suggested_action: Mapped[Optional[str]] = mapped_column(String(255), nullable=True)
    disqualify: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    disqualify_reason: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=False),
        default=datetime.utcnow,
        nullable=False,
    )

    # Relationships
    lead: Mapped["Lead"] = relationship("Lead", back_populates="composite_score")

    def __repr__(self) -> str:
        """Return string representation of the CompositeScore."""
        return f"<CompositeScore(id={self.id}, lead_id={self.lead_id}, score={self.composite_score})>"
